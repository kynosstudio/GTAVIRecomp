  const sourceByText = new WeakMap();
  const sourceByAttribute = new WeakMap();

  function translateText(value, language) {
    if (language === 'pt') return value;
    const dictionary = dictionaries[language];
    if (!dictionary) return value;
    const leading = value.match(/^\s*/)[0];
    const trailing = value.match(/\s*$/)[0];
    const source = value.trim();
    if (!source) return value;
    if (dictionary[source]) return language === 'zh'
      ? dictionary[source]
      : `${leading}${dictionary[source]}${trailing}`;

    let translated = source
      .replace(/· (\d+)ª geração/g, (_, generation) => `· ${generation}${language === 'en' ? (generation === '1' ? 'st' : generation === '2' ? 'nd' : generation === '3' ? 'rd' : 'th') + ' gen' : language === 'es' ? 'ª generación' : ' 代'}`)
      .replace(/· Série (\d+)/g, (_, series) => `· ${language === 'en' ? 'Series' : language === 'es' ? 'Serie' : '系列'} ${series}`)
      .replace(/(\d+) nov\b/g, (_, day) => language === 'en' ? `Nov ${day}` : language === 'es' ? `${day} nov` : `11月${day}日`)
      .replace(/ \[(?:iGPU|Sem iGPU)\]/g, (match) => dictionary[match.trim()] ? ` [${dictionary[match.trim()].replace(/^\[|\]$/g, '')}]` : match);
    translated = translated
      .replace(/^Menos de (\d+) GB$/, (_, amount) => language === 'en' ? `Less than ${amount} GB` : language === 'es' ? `Menos de ${amount} GB` : `少于 ${amount} GB`)
      .replace(/^(\d+) GB \(requisito estimado\)$/, (_, amount) => language === 'en' ? `${amount} GB (estimated requirement)` : language === 'es' ? `${amount} GB (requisito estimado)` : `${amount} GB（估算要求）`)
      .replace(/^(\d+) GB livres$/, (_, amount) => language === 'en' ? `${amount} GB free` : language === 'es' ? `${amount} GB libres` : `${amount} GB 可用`)
      .replace(/^Até (.+)$/, (_, speed) => language === 'en' ? `Up to ${speed}` : language === 'es' ? `Hasta ${speed}` : `最高 ${speed}`);

    Object.keys(dictionary).sort((left, right) => right.length - left.length).forEach((phrase) => {
      if (phrase.length > 3 && translated.includes(phrase)) translated = translated.split(phrase).join(dictionary[phrase]);
    });
    return language === 'zh' ? translated.trim() : `${leading}${translated}${trailing}`;
  }

  function translateDom(root, language) {
    if (root.nodeType === Node.ELEMENT_NODE && root.closest('[translate="no"]')) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return node.parentElement && node.parentElement.closest('[translate="no"]')
          ? NodeFilter.FILTER_REJECT
          : NodeFilter.FILTER_ACCEPT;
      }
    });
    let node;
    while ((node = walker.nextNode())) {
      let source = sourceByText.get(node);
      if (!source) {
        source = { value: node.nodeValue, last: node.nodeValue };
        sourceByText.set(node, source);
      } else if (node.nodeValue !== source.last) {
        source.value = node.nodeValue;
      }
      node.nodeValue = translateText(source.value, language);
      source.last = node.nodeValue;
    }
    root.querySelectorAll('*').forEach((element) => {
      if (element.closest('[translate="no"]')) return;
      const sourceAttributes = sourceByAttribute.get(element) || {};
      ['aria-label', 'title', 'alt', 'placeholder', 'data-tooltip', 'label'].forEach((attribute) => {
        const current = element.getAttribute(attribute);
        if (current === null) return;
        let source = sourceAttributes[attribute];
        if (!source) {
          source = { value: current, last: current };
          sourceAttributes[attribute] = source;
        } else if (current !== source.last) {
          source.value = current;
        }
        element.setAttribute(attribute, translateText(source.value, language));
        source.last = element.getAttribute(attribute);
      });
      sourceByAttribute.set(element, sourceAttributes);
    });
  }

  window.KynosI18n = { translateText, translateDom };
